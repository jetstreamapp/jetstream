import type { NextFunction, Request, Response } from 'express';

export type FaviconEnvironment = 'development' | 'staging' | 'production';

// `favicon.ico` and the sized `favicon-32x32.png` set, with or without a query string
const FAVICON_PATH_RE = /^\/favicon(\.ico|-\d+x\d+\.png)(?=$|\?)/;

/**
 * Maps a favicon path (relative to `/assets/images`) to the file for this environment, e.g. `/favicon-32x32.png` to
 * `/favicon-staging-32x32.png`. Every other path, and every path in production, is returned unchanged.
 */
export function getEnvironmentFaviconPath(path: string, environment: FaviconEnvironment): string {
  if (environment === 'production') {
    return path;
  }
  return path.replace(FAVICON_PATH_RE, `/favicon-${environment}$1`);
}

/**
 * Serves the development or staging favicons in place of the production ones, so a non-production tab is never
 * mistaken for production. The swap happens on the image request rather than in the HTML because every page shares
 * these URLs: the web app shell, the statically exported landing and auth pages, and both dev servers, which proxy
 * `/assets` here. Mount on `/assets/images` ahead of the static handler. Files are generated by `pnpm icons:brand`.
 */
export function environmentFaviconMiddleware(environment: FaviconEnvironment) {
  return (req: Request, _res: Response, next: NextFunction) => {
    req.url = getEnvironmentFaviconPath(req.url, environment);
    next();
  };
}
